import { Router } from "express";
import { openai } from "@workspace/integrations-openai-ai-server";
import { AnalyzeTextBody } from "@workspace/api-zod";
import { requireAuth } from "../../middlewares/requireAuth";

const router = Router();

router.post("/analyze", requireAuth, async (req, res) => {
  const parsed = AnalyzeTextBody.safeParse(req.body);
  if (!parsed.success) {
    res.status(400).json({ error: "Invalid request body" });
    return;
  }

  const { text, writingType } = parsed.data;

  const systemPrompt = `You are an expert linguist and AI-detection specialist. You analyze text to determine whether it was written by a human or generated by an AI. You are highly skilled at identifying telltale signs of AI writing across all genres: poems, essays, academic papers, blog posts, stories, letters, articles, social media posts, speeches, and technical writing. You provide detailed, honest assessments.`;

  const userPrompt = `Analyze the following ${writingType} for signs of AI generation. Be thorough and specific.

TEXT TO ANALYZE:
"""
${text}
"""

Return a JSON object with EXACTLY this structure (no markdown, just raw JSON):
{
  "aiProbability": <number 0-100, where 0=definitely human, 100=definitely AI>,
  "label": "<one of: human, likely-human, mixed, likely-ai, ai>",
  "summary": "<1-2 paragraph plain-English explanation of your verdict, mentioning specific evidence>",
  "reasons": [
    "<specific reason 1 — e.g. 'Uniform sentence rhythm with no natural variation'>",
    "<specific reason 2>",
    "<specific reason 3>",
    ...at least 4 reasons total
  ],
  "signals": [
    {
      "phrase": "<exact short phrase or sentence excerpt from the text that is a signal>",
      "reason": "<why this specific phrase reads as AI-generated or human>"
    },
    ...at least 3 signals, up to 8
  ]
}

Label guide:
- human: 0-20% probability
- likely-human: 21-40%
- mixed: 41-60%
- likely-ai: 61-80%
- ai: 81-100%

Be honest and specific. For a poem, consider line breaks, emotional authenticity, unexpected imagery vs clichéd metaphors. For an essay/academic, consider argument structure, hedging language, generic transitions. For blog/social, consider personality and voice.`;

  try {
    const completion = await openai.chat.completions.create({
      model: "gpt-5.6-terra",
      max_completion_tokens: 4096,
      messages: [
        { role: "system", content: systemPrompt },
        { role: "user", content: userPrompt },
      ],
      response_format: { type: "json_object" },
    });

    const content = completion.choices[0]?.message?.content;
    if (!content) {
      res.status(500).json({ error: "No response from AI" });
      return;
    }

    const data = JSON.parse(content);
    res.json(data);
  } catch (err) {
    req.log.error({ err }, "Failed to analyze text");
    res.status(500).json({ error: "Failed to analyze text" });
  }
});

export default router;
